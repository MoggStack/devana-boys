#!/usr/bin/env node
/* Scans assets/faces/* and assets/sounds/* and writes js/manifest.js
   so the game knows which files exist (browsers can't list folders).
   Runs automatically on Vercel deploy; run it locally after adding files:
       node scripts/build-manifest.js                                    */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const IMG = /\.(png|jpe?g|webp|gif|avif)$/i;
const AUD = /\.(mp3|ogg|wav|m4a|aac|webm|opus)$/i;

function list(dir, re) {
  const abs = path.join(ROOT, dir);
  if (!fs.existsSync(abs)) return [];
  return fs
    .readdirSync(abs)
    .filter((f) => re.test(f) && !f.startsWith("."))
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }))
    .map((f) => dir.split("/").concat(f).map(encodeURIComponent).join("/"));
}

const soundsDir = path.join(ROOT, "assets/sounds");
const sounds = {};
if (fs.existsSync(soundsDir)) {
  for (const cat of fs.readdirSync(soundsDir)) {
    if (fs.statSync(path.join(soundsDir, cat)).isDirectory()) {
      sounds[cat] = list(`assets/sounds/${cat}`, AUD);
    }
  }
}

const manifest = {
  faces: {
    sleeper: list("assets/faces/sleeper", IMG),
    mosquitos: list("assets/faces/mosquitos", IMG),
  },
  sounds,
};

fs.writeFileSync(
  path.join(ROOT, "js/manifest.js"),
  "/* AUTO-GENERATED by scripts/build-manifest.js — do not edit */\n" +
    "window.ASSET_MANIFEST = " + JSON.stringify(manifest, null, 2) + ";\n"
);

console.log(
  `faces: sleeper ${manifest.faces.sleeper.length}, mosquitos ${manifest.faces.mosquitos.length}\n` +
    Object.entries(sounds).map(([k, v]) => `sounds/${k}: ${v.length}`).join("\n")
);
